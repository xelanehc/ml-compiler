// Loop IR -> C++ text. Serial loops are transcribed directly: each For becomes
// a for loop, each Store an assignment, each multi-dimensional access one flat
// subscript. A vectorized loop becomes a loop over SIMD intrinsics followed by
// a scalar loop for the leftover iterations; a parallel loop becomes a
// function of an index range, handed to the runtime's thread pool.
//
// No decision is made here. Which loops are vectorized or parallel was decided
// by the schedule (loop/schedule.h); this file only spells it out.
#include <cmath>
#include <cstdio>
#include <cstring>
#include <map>
#include <sstream>

#include "codegen/codegen.h"
#include "codegen/isa.h"
#include "loop/schedule.h"

