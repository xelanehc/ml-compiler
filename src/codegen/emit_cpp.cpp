// Loop IR -> C++ text. A direct transcription: each For becomes a for loop,
// each Store an assignment, each multi-dimensional access one flat subscript.
// Nothing is optimized here; whatever speed the result has comes from the
// loop program it was given and from the C++ compiler.
#include <cmath>
#include <cstdio>
#include <cstring>
#include <map>
#include <sstream>

#include "codegen/codegen.h"

namespace mlc::codegen {

using namespace mlc::loop;

namespace {

const char* c_type(DType d) {
  switch (d) {
    case DType::F32: return "float";
    case DType::I64: return "int64_t";
    case DType::Bool: return "uint8_t";
  }
  return "?";
}

// A float literal that reads back as exactly the same f32. Nine significant
// digits are always enough to round-trip a 32-bit float.
std::string float_literal(double v) {
  if (std::isnan(v)) return "NAN";
  if (std::isinf(v)) return v > 0 ? "INFINITY" : "(-INFINITY)";
  char buf[40];
  std::snprintf(buf, sizeof buf, "%.9g", v);
  std::string s = buf;
  if (s.find_first_of(".e") == std::string::npos) s += ".0";
  s += "f";
  return v < 0 ? "(" + s + ")" : s;
}

std::string int_literal(int64_t v) {
  std::string s = std::to_string(v);
  if (v > INT32_MAX || v < INT32_MIN) s += "LL";
  return v < 0 ? "(" + s + ")" : s;
}

std::string quoted(const std::string& s) {
  std::string out = "\"";
  for (char c : s) {
    if (c == '"' || c == '\\') out += '\\';
    out += c;
  }
  return out + "\"";
}

class Emitter {
 public:
  explicit Emitter(const Program& p) : p_(p) {}

  std::string run() {
    out_ << "// Generated by mlc. Do not edit: change the compiler and regenerate.\n"
         << "// " << p_.kernels.size() << " kernels, " << p_.arena_bytes << " bytes of arena.\n"
         << "#include <cmath>\n#include <cstdint>\n\n#include \"mlc_runtime.h\"\n\n"
         << "namespace {\n\n"
         << "inline float mlc_max(float a, float b) { return a > b ? a : b; }\n\n";
    emit_inline_constants();
    for (size_t k = 0; k < p_.kernels.size(); ++k) emit_kernel(k);
    emit_table();
    return out_.str();
  }

 private:
  const Program& p_;
  std::ostringstream out_;

  static std::string kernel_name(size_t k, const Kernel& kernel) { return "k" + std::to_string(k) + "_" + kernel.op; }

  // Small constant tables (position ids and the like) become static arrays.
  // Weights never do: they stay in the weights file and are addressed by offset.
  void emit_inline_constants() {
    std::map<int32_t, const Buffer*> used;
    for (const Kernel& k : p_.kernels) {
      std::map<BufferId, bool> refs;
      collect(k.body, refs);
      for (auto& [id, written] : refs)
        if (p_.buffers[id].storage == Storage::Inline) used.emplace(p_.buffers[id].index, &p_.buffers[id]);
    }
    for (auto& [index, buffer] : used) {
      const std::vector<std::byte>& data = p_.inline_data[index];
      size_t count = data.size() / dtype_size(buffer->dtype);
      out_ << "const " << c_type(buffer->dtype) << " inline_" << index << "[" << count << "] = {";
      for (size_t i = 0; i < count; ++i) {
        if (i) out_ << ", ";
        const std::byte* at = data.data() + i * dtype_size(buffer->dtype);
        switch (buffer->dtype) {
          case DType::F32: { float v; std::memcpy(&v, at, sizeof v); out_ << float_literal(v); break; }
          case DType::I64: { int64_t v; std::memcpy(&v, at, sizeof v); out_ << int_literal(v); break; }
          case DType::Bool: out_ << (at[0] != std::byte{0} ? 1 : 0); break;
        }
      }
      out_ << "};\n";
    }
    if (!used.empty()) out_ << "\n";
  }

  // Which buffers a kernel touches, and whether it writes each one.
  void collect(const ExprPtr& e, std::map<BufferId, bool>& refs) const {
    if (e->kind == ExprKind::Load) refs.emplace(e->buffer, false);
    for (const ExprPtr& a : e->args) collect(a, refs);
  }

  void collect(const StmtPtr& s, std::map<BufferId, bool>& refs) const {
    switch (s->kind) {
      case StmtKind::For: collect(s->body, refs); break;
      case StmtKind::Store:
        refs[s->buffer] = true;
        for (const ExprPtr& i : s->indices) collect(i, refs);
        collect(s->value, refs);
        break;
      case StmtKind::Block:
        for (const StmtPtr& child : s->stmts) collect(child, refs);
        break;
    }
  }

  // Turns a buffer into a typed pointer at the top of the kernel:
  //   float* const v75 = (float*)(arena + 8192);
  void emit_pointer(const Buffer& b, bool written) {
    std::string type = std::string(written ? "" : "const ") + c_type(b.dtype) + "*";
    out_ << "  " << type << " const " << b.name << " = ";
    switch (b.storage) {
      case Storage::Arena: out_ << "(" << type << ")(arena + " << b.offset << ")"; break;
      case Storage::Weights: out_ << "(" << type << ")(weights + " << b.offset << ")"; break;
      case Storage::Input: out_ << "(" << type << ")inputs[" << b.index << "]"; break;
      case Storage::Output: out_ << "(" << type << ")outputs[" << b.index << "]"; break;
      case Storage::Inline: out_ << "inline_" << b.index; break;
    }
    out_ << ";\n";
  }

  std::string access(BufferId id, const std::vector<ExprPtr>& indices) {
    const Buffer& b = p_.buffers[id];
    return b.name + "[" + expr(flat_index(b, indices)) + "]";
  }

  std::string expr(const ExprPtr& e) {
    switch (e->kind) {
      case ExprKind::IntImm: return int_literal(e->int_value);
      case ExprKind::FloatImm: return float_literal(e->float_value);
      case ExprKind::Var: return "i" + std::to_string(e->var);
      case ExprKind::Load: return access(e->buffer, e->args);
      case ExprKind::Binary: {
        std::string a = expr(e->args[0]), b = expr(e->args[1]);
        switch (e->binop) {
          case BinOp::Add: return "(" + a + " + " + b + ")";
          case BinOp::Sub: return "(" + a + " - " + b + ")";
          case BinOp::Mul: return "(" + a + " * " + b + ")";
          case BinOp::Div: return "(" + a + " / " + b + ")";
          case BinOp::Max: return "mlc_max(" + a + ", " + b + ")";
          // Comparisons and logic produce bool, which is stored as one byte.
          case BinOp::Eq: return "(uint8_t)(" + a + " == " + b + ")";
          case BinOp::Ne: return "(uint8_t)(" + a + " != " + b + ")";
          case BinOp::Le: return "(uint8_t)(" + a + " <= " + b + ")";
          case BinOp::And: return "(uint8_t)(" + a + " & " + b + ")";
          case BinOp::Or: return "(uint8_t)(" + a + " | " + b + ")";
        }
        break;
      }
      case ExprKind::Not: return "(uint8_t)(!" + expr(e->args[0]) + ")";
      case ExprKind::Call: {
        // The arguments are float, so these resolve to the float overloads.
        std::string a = expr(e->args[0]);
        switch (e->intrinsic) {
          case Intrinsic::Exp: return "std::exp(" + a + ")";
          case Intrinsic::Tanh: return "std::tanh(" + a + ")";
          case Intrinsic::Sqrt: return "std::sqrt(" + a + ")";
          case Intrinsic::Pow: return "std::pow(" + a + ", " + expr(e->args[1]) + ")";
        }
        break;
      }
      case ExprKind::Select: return "(" + expr(e->args[0]) + " ? " + expr(e->args[1]) + " : " + expr(e->args[2]) + ")";
      case ExprKind::Cast:
        if (e->type == DType::Bool) return "(uint8_t)(" + expr(e->args[0]) + " != 0)";
        return std::string("(") + c_type(e->type) + ")(" + expr(e->args[0]) + ")";
    }
    throw CodegenError("cannot emit expression");
  }

  void stmt(const StmtPtr& s, int depth) {
    std::string pad(static_cast<size_t>(depth) * 2, ' ');
    switch (s->kind) {
      case StmtKind::For: {
        if (s->loop_kind != LoopKind::Serial) throw CodegenError("only serial loops can be emitted so far");
        std::string v = "i" + std::to_string(s->var);
        out_ << pad << "for (int64_t " << v << " = 0; " << v << " < " << s->extent << "; ++" << v << ") {\n";
        stmt(s->body, depth + 1);
        out_ << pad << "}\n";
        break;
      }
      case StmtKind::Store: out_ << pad << access(s->buffer, s->indices) << " = " << expr(s->value) << ";\n"; break;
      case StmtKind::Block:
        for (const StmtPtr& child : s->stmts) stmt(child, depth);
        break;
    }
  }

  void emit_kernel(size_t k) {
    const Kernel& kernel = p_.kernels[k];
    std::map<BufferId, bool> refs;
    collect(kernel.body, refs);
    out_ << "// " << kernel.label << "\n"
         << "void " << kernel_name(k, kernel)
         << "([[maybe_unused]] char* arena, [[maybe_unused]] const char* weights,\n"
         << "    [[maybe_unused]] const void* const* inputs, [[maybe_unused]] void* const* outputs) {\n";
    for (auto& [id, written] : refs) emit_pointer(p_.buffers[id], written);
    stmt(kernel.body, 1);
    out_ << "}\n\n";
  }

  void emit_sizes(const char* name, const std::vector<Type>& types) {
    out_ << "const int64_t " << name << "[] = {";
    for (size_t i = 0; i < types.size(); ++i) out_ << (i ? ", " : "") << types[i].byte_size();
    if (types.empty()) out_ << "0";  // C++ has no zero-length arrays
    out_ << "};\n";
  }

  void emit_table() {
    out_ << "const mlc_kernel kernels[] = {\n";
    for (size_t k = 0; k < p_.kernels.size(); ++k)
      out_ << "  {" << quoted(p_.kernels[k].op) << ", " << quoted(p_.kernels[k].label) << ", " << kernel_name(k, p_.kernels[k]) << "},\n";
    if (p_.kernels.empty()) out_ << "  {nullptr, nullptr, nullptr},\n";
    out_ << "};\n\n";
    emit_sizes("input_bytes", p_.inputs);
    emit_sizes("output_bytes", p_.outputs);
    out_ << "\n}  // namespace\n\n"
         << "extern \"C\" const mlc_model_desc mlc_gen_model = {\n"
         << "  " << p_.arena_bytes << ",  // arena_bytes\n"
         << "  " << p_.weights_bytes << ",  // weights_bytes\n"
         << "  " << p_.inputs.size() << ", " << p_.outputs.size() << ",  // inputs, outputs\n"
         << "  input_bytes, output_bytes,\n"
         << "  " << p_.kernels.size() << ", kernels,\n"
         << "};\n";
  }
};

}  // namespace

std::string emit_cpp(const Program& p) {
  check_program(p);
  return Emitter(p).run();
}

}  // namespace mlc::codegen
